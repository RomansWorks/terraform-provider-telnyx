// Catalog is the content of catalog/resources.yaml.
type Catalog struct {
	UpstreamCommit string     `yaml:"upstream_commit"`
	Resources      []Resource `yaml:"resources"`
}

// Save writes the catalog with a header.
func (c Catalog) Save(path string) error {
	data, err := yaml.Marshal(c)
	if err != nil {
		return err
	}
	header := "# Generated by `make catalog` from upstream/telnyx/spec3.json. Do not edit.\n" +
		"# Candidate Terraform resources detected from path shapes. Names are\n" +
		"# suggestions; generator overrides decide the final schema.\n"
	return os.WriteFile(path, append([]byte(header), data...), 0o644)
}

// Diff summarises how the API changed between two spec versions, in the
// terms the provider cares about.
type Diff struct {
	OpsAdded, OpsRemoved, OpsChanged, OpsDeprecated []string
	ResAdded, ResRemoved, ResChanged                []string
	OldCommit, NewCommit                            string
	CoverageAdded                                   []string
}

// Empty reports whether nothing relevant changed.
func (d Diff) Empty() bool {
	return len(d.OpsAdded)+len(d.OpsRemoved)+len(d.OpsChanged)+len(d.OpsDeprecated) == 0
}

// Compare computes the Diff between two specs.
func Compare(oldSpec, newSpec *Spec) Diff {
	var d Diff
	oldOps, newOps := opIndex(oldSpec), opIndex(newSpec)
	for _, k := range sortedKeys(newOps) {
		n := newOps[k]
		o, ok := oldOps[k]
		switch {
		case !ok:
			d.OpsAdded = append(d.OpsAdded, k)
		case oldSpec.Hash(o.Node) != newSpec.Hash(n.Node):
			d.OpsChanged = append(d.OpsChanged, k)
		}
		if n.Deprecated && (!ok || !o.Deprecated) {
			d.OpsDeprecated = append(d.OpsDeprecated, k)
		}
	}
	for _, k := range sortedKeys(oldOps) {
		if _, ok := newOps[k]; !ok {
			d.OpsRemoved = append(d.OpsRemoved, k)
		}
	}

	oldRes, newRes := resIndex(DetectResources(oldSpec)), resIndex(DetectResources(newSpec))
	for _, k := range sortedKeys(newRes) {
		o, ok := oldRes[k]
		switch {
		case !ok:
			d.ResAdded = append(d.ResAdded, k)
		case o.SchemaHash != newRes[k].SchemaHash:
			d.ResChanged = append(d.ResChanged, k)
		}
	}
	for _, k := range sortedKeys(oldRes) {
		if _, ok := newRes[k]; !ok {
			d.ResRemoved = append(d.ResRemoved, k)
		}
	}
	return d
}

// Markdown renders the diff as the api-diff.md that starts an OpenSpec sync
// change.
func (d Diff) Markdown() string {
	var b strings.Builder
	b.WriteString("# Telnyx API changes\n\n")
	fmt.Fprintf(&b, "Upstream `team-telnyx/openapi` from `%s` to `%s`.\n\n", short(d.OldCommit), short(d.NewCommit))
	if d.Empty() {
		b.WriteString("No operation changed.\n")
		return b.String()
	}
	fmt.Fprintf(&b, "| Change | Count |\n|---|---|\n| Operations added | %d |\n| Operations removed | %d |\n| Operations changed | %d |\n| Newly deprecated | %d |\n| Candidate resources added | %d |\n| Candidate resources removed | %d |\n| Candidate resources changed | %d |\n\n",
		len(d.OpsAdded), len(d.OpsRemoved), len(d.OpsChanged), len(d.OpsDeprecated), len(d.ResAdded), len(d.ResRemoved), len(d.ResChanged))
	section := func(title, hint string, items []string) {
		if len(items) == 0 {
			return
		}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", title, hint)
		for _, i := range items {
			fmt.Fprintf(&b, "- `%s`\n", i)
		}
		b.WriteString("\n")
	}
	section("Candidate resources added", "Each needs a spec requirement, an override file and tests, or a coverage note explaining why not.", d.ResAdded)
	section("Candidate resources removed", "Removing a resource is a breaking change: deprecate first, remove in the next major release.", d.ResRemoved)
	section("Candidate resources changed", "Request or response schema changed. Regenerate and check for new, removed or retyped attributes.", d.ResChanged)
	section("Operations removed", "Check coverage.yaml history for the Terraform type that used each one.", d.OpsRemoved)
	section("Operations newly deprecated", "Mirror the deprecation on the matching attribute or resource.", d.OpsDeprecated)
	section("Operations added", "Added to coverage.yaml with reviewed: false. Confirm each bucket.", d.OpsAdded)
	section("Operations changed", "Schema or parameters changed.", d.OpsChanged)
	return b.String()
}

func opIndex(s *Spec) map[string]Operation {
	m := map[string]Operation{}
	for _, o := range s.Operations() {
		m[o.Key()] = o
	}
	return m
}

func resIndex(rs []Resource) map[string]Resource {
	m := map[string]Resource{}
	for _, r := range rs {
		m[r.ItemPath] = r
	}
	return m
}

func short(c string) string {
	if len(c) > 7 {
		return c[:7]
	}
	if c == "" {
		return "(none)"
	}
	return c
}
